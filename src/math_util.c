#define MT_UMASK         (0xFFFFFFFF << MT_R)
#define MT_LMASK         (0xFFFFFFFF >> (MT_W - MT_R))
#define MT_DEFAULT_SEED  5489

static u32 sMTRNGState[MT_N];
static int sMTRNGIndex = MT_N + 1;
static u32 sMTRNGXor[2] = { 0, MT_A };

void MTRNG_SetSeed(u32 seed) {
	sMTRNGState[0] = seed;
	for (sMTRNGIndex = 1; sMTRNGIndex < MT_N; sMTRNGIndex++) {
		sMTRNGState[sMTRNGIndex] = MT_F * (sMTRNGState[sMTRNGIndex - 1] ^ (sMTRNGState[sMTRNGIndex - 1] >> (MT_W - 2))) + sMTRNGIndex;
	}
}


u32 MTRNG_Next(void) {
	u32 result;
	if (sMTRNGIndex >= MT_N) {
		if (sMTRNGIndex == MT_N + 1) {
			MTRNG_SetSeed(MT_DEFAULT_SEED);
		}
		
		int i;
		for (i = 0; i < MT_N - MT_M; i++) {
			result = (sMTRNGState[i] & MT_UMASK) | (sMTRNGState[i + 1] & MT_LMASK);
			sMTRNGState[i] = sMTRNGState[i + MT_M] ^ (result >> 1) ^ sMTRNGXor[result & 1];
		}
		for (; i < MT_N - 1; i++) {
			result = (sMTRNGState[i] & MT_UMASK) | (sMTRNGState[i + 1] & MT_LMASK);
			sMTRNGState[i] = sMTRNGState[i + (MT_M - MT_N)] ^ (result >> 1) ^ sMTRNGXor[result & 1];
		}
		
		result = (sMTRNGState[MT_N - 1] & MT_UMASK) | (sMTRNGState[0] & MT_LMASK);
		sMTRNGState[MT_N - 1] = sMTRNGState[MT_M - 1] ^ (result >> 1) ^ sMTRNGXor[result & 1];
		sMTRNGIndex = 0;
	}
	
	result = sMTRNGState[sMTRNGIndex++];
	result ^= (result >> MT_U);
	result ^= (result << MT_S) & MT_B;
	result ^= (result << MT_T) & MT_C;
	result ^= (result >> MT_L);
	
	return result;
}


void CreateAffineTransformationMatrix(MtxFx22* matrix, u16 degrees, fx32 xScale, fx32 yScale, u8 mode) {
	if (mode == AFFINE_MODE_MAX_256) {
		degrees = (u32)(0xFFFF * degrees) >> 8;
	} else if (mode == AFFINE_MODE_MAX_360) {
		degrees = (u32)(0xFFFF * degrees) / 360;
	}
	
	MTX_Rot22(matrix, FX_SinIdx(degrees), FX_CosIdx(degrees));
	MTX_ScaleApply22(matrix, matrix, xScale, yScale);
}
